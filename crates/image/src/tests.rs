#[test]
fn refuses_what_it_cannot_or_should_not_decode() {
    assert!(decode_png(b"not a png at all").is_err());
    assert!(decode_png(&[]).is_err());
    // Interlaced.
    let mut ihdr = 1u32.to_be_bytes().to_vec();
    ihdr.extend_from_slice(&1u32.to_be_bytes());
    ihdr.extend_from_slice(&[8, 0, 0, 0, 1]);
    let mut f = vec![0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a];
    f.extend(chunk(b"IHDR", &ihdr));
    assert_eq!(
        decode_png(&f),
        Err(ImageError::Unsupported("interlaced PNG"))
    );
    // A bad checksum.
    let mut bad = GRADIENT.to_vec();
    let n = bad.len();
    bad[n - 20] ^= 0xff;
    assert!(decode_png(&bad).is_err());
    // A decompression bomb: tiny file, enormous claimed size.
    let huge = png(16_384, 16_384, 8, 6, &[], &[0]);
    assert_eq!(decode_png(&huge), Err(ImageError::TooLarge));
    // Wrong amount of data for the size.
    assert!(decode_png(&png(4, 4, 8, 6, &[], &[0; 10])).is_err());
    // Palette image with an index past the palette.
    assert!(decode_png(&png(1, 1, 8, 3, &[(b"PLTE", &[1, 2, 3])], &[0, 5])).is_err());
}

#[test]
fn inflate_handles_stored_fixed_and_rejects_garbage() {
    // "abc" as a fixed-Huffman block, from zlib.
    let fixed = [
        0x78, 0x9c, 0x4b, 0x4c, 0x4a, 0x06, 0x00, 0x02, 0x4d, 0x01, 0x27,
    ];
    assert_eq!(zlib_decompress(&fixed, 100).unwrap(), b"abc");
    assert_eq!(zlib_decompress(&fixed, 2), Err(ImageError::TooLarge));
    assert_eq!(
        zlib_decompress(&zlib_stored(b"hello"), 100).unwrap(),
        b"hello"
    );
    assert!(zlib_decompress(&[0x78], 10).is_err());
    assert!(zlib_decompress(&[0x00, 0x00, 1, 2, 3], 10).is_err());
    // A flipped checksum.
    let mut s = zlib_stored(b"hello");
    let n = s.len();
    s[n - 1] ^= 1;
    assert!(zlib_decompress(&s, 100).is_err());
}

