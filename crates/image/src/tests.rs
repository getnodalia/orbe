fn crc32(parts: &[&[u8]]) -> u32 {
    let mut crc = 0xffff_ffffu32;
    for part in parts {
        for &b in *part {
            crc ^= u32::from(b);
            for _ in 0..8 {
                crc = if crc & 1 != 0 {
                    (crc >> 1) ^ 0xedb8_8320
                } else {
                    crc >> 1
                };
            }
        }
    }
    !crc
}

fn chunk(kind: &[u8], data: &[u8]) -> Vec<u8> {
    let mut v = (data.len() as u32).to_be_bytes().to_vec();
    v.extend_from_slice(kind);
    v.extend_from_slice(data);
    v.extend_from_slice(&crc32(&[kind, data]).to_be_bytes());
    v
}

fn adler(data: &[u8]) -> u32 {
    let (mut a, mut b) = (1u32, 0u32);
    for &x in data {
        a = (a + u32::from(x)) % 65_521;
        b = (b + a) % 65_521;
    }
    (b << 16) | a
}

/// A zlib stream of stored (uncompressed) blocks.
fn zlib_stored(data: &[u8]) -> Vec<u8> {
    let mut v = vec![0x78, 0x01];
    let mut chunks = data.chunks(65_535).peekable();
    if chunks.peek().is_none() {
        v.extend_from_slice(&[1, 0, 0, 0xff, 0xff]);
    }
    while let Some(c) = chunks.next() {
        v.push(u8::from(chunks.peek().is_none()));
        v.extend_from_slice(&(c.len() as u16).to_le_bytes());
        v.extend_from_slice(&(!(c.len() as u16)).to_le_bytes());
        v.extend_from_slice(c);
    }
    v.extend_from_slice(&adler(data).to_be_bytes());
    v
}

fn png(w: u32, h: u32, depth: u8, color: u8, extra: &[(&[u8], &[u8])], raw: &[u8]) -> Vec<u8> {
    let mut ihdr = w.to_be_bytes().to_vec();
    ihdr.extend_from_slice(&h.to_be_bytes());
    ihdr.extend_from_slice(&[depth, color, 0, 0, 0]);
    let mut out = vec![0x89, b'P', b'N', b'G', 0x0d, 0x0a, 0x1a, 0x0a];
    out.extend(chunk(b"IHDR", &ihdr));
    for (k, d) in extra {
        out.extend(chunk(k, d));
    }
    out.extend(chunk(b"IDAT", &zlib_stored(raw)));
    out.extend(chunk(b"IEND", &[]));
    out
}

#[test]
fn compressed_gradient_with_every_filter_decodes_exactly() {
    let img = decode_png(GRADIENT).unwrap();
    assert_eq!((img.width, img.height), (32, 32));
    for y in 0..32u32 {
        for x in 0..32u32 {
            let i = ((y * 32 + x) * 4) as usize;
            let want = [
                ((x * 8) % 256) as u8,
                ((y * 8) % 256) as u8,
                ((x * y) % 256) as u8,
                (255 - ((x + y) % 64)) as u8,
            ];
            assert_eq!(img.rgba[i..i + 4], want, "pixel {x},{y}");
        }
    }
}

#[test]
fn colour_types_and_depths() {
    // Grey 1-bit: 8 pixels in one byte.
    let g1 = decode_png(&png(8, 1, 1, 0, &[], &[0, 0b1010_0000])).unwrap();
    assert_eq!(&g1.rgba[..4], &[255, 255, 255, 255]);
    assert_eq!(&g1.rgba[4..8], &[0, 0, 0, 255]);
    // Grey 16-bit takes the high byte.
    let g16 = decode_png(&png(1, 1, 16, 0, &[], &[0, 0x80, 0xff])).unwrap();
    assert_eq!(&g16.rgba[..], &[0x80, 0x80, 0x80, 255]);
    // Palette 2-bit with transparency.
    let pal = decode_png(&png(
        2,
        1,
        2,
        3,
        &[(b"PLTE", &[255, 0, 0, 0, 255, 0]), (b"tRNS", &[128])],
        &[0, 0b0001_0000],
    ))
    .unwrap();
    assert_eq!(&pal.rgba[..], &[255, 0, 0, 128, 0, 255, 0, 255]);
    // Grey + alpha and RGB with a colour key.
    let ga = decode_png(&png(1, 1, 8, 4, &[], &[0, 10, 20])).unwrap();
    assert_eq!(&ga.rgba[..], &[10, 10, 10, 20]);
    let key = decode_png(&png(
        2,
        1,
        8,
        2,
        &[(b"tRNS", &[0, 1, 0, 2, 0, 3])],
        &[0, 1, 2, 3, 4, 5, 6],
    ))
    .unwrap();
    assert_eq!(&key.rgba[..], &[1, 2, 3, 0, 4, 5, 6, 255]);
}

